-- Script SQL untuk membuat tabel jadwal_ngajar di Supabase

CREATE TABLE public.jadwal_ngajar (
    id bigint generated by default as identity primary key,
    nama_murid text not null,
    mata_pelajaran text not null,
    materi text,
    jam timestamp with time zone not null,
    laporan_akhir text,
    user_id bigint default 1,
    notif_sent boolean default false,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Mengaktifkan Row Level Security (RLS)
ALTER TABLE public.jadwal_ngajar ENABLE ROW LEVEL SECURITY;

-- Membuat policy agar aplikasi bisa melakukan Create, Read, Update, Delete (CRUD)
-- Catatan: Policy ini mengizinkan akses anonim (untuk development/testing).
-- Jika aplikasi menggunakan otentikasi Supabase Auth, ganti "true" dengan auth.uid() = user_id atau sesuai kebutuhan.
CREATE POLICY "Enable all operations for anon users" 
ON public.jadwal_ngajar 
FOR ALL 
USING (true) 
WITH CHECK (true);
